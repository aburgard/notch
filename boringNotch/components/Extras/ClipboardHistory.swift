//
//  ClipboardHistory.swift
//  boringNotch
//
//  Keeps the last items copied on this Mac. macOS has no "clipboard changed"
//  notification, so this checks the pasteboard's change count twice a second,
//  which is the standard approach and costs almost nothing.
//
//  Privacy: items that password managers and other apps mark as concealed or
//  transient (the nspasteboard.org convention) are never recorded. Text items
//  are saved to the app's own sandbox container so history survives a restart;
//  images stay in memory only.
//

import AppKit
import Foundation

struct ClipboardItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, image, files }

    let id: UUID
    let kind: Kind
    let text: String?          // text, link, or newline-separated file paths
    let sourceApp: String?
    let copiedAt: Date
    var pinned: Bool
    var imageData: Data?       // PNG; not persisted

    enum CodingKeys: String, CodingKey { case id, kind, text, sourceApp, copiedAt, pinned }

    var preview: String {
        switch kind {
        case .text, .link: return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        case .files:
            let names = (text ?? "").split(separator: "\n").map { URL(fileURLWithPath: String($0)).lastPathComponent }
            return names.joined(separator: ", ")
        case .image: return "Image"
        }
    }

    var fileURLs: [URL] {
        guard kind == .files, let text else { return [] }
        return text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) }
    }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [ClipboardItem] = []

    /// Unpinned items kept. Pinned items don't count toward this.
    let limit = 50

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var ignoreNextChange = false

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    private var storeURL: URL? {
        guard let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first else { return nil }
        let folder = dir.appendingPathComponent("NotchExtras", isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return folder.appendingPathComponent("clipboard.json")
    }

    private init() {
        lastChangeCount = pasteboard.changeCount
        load()
        start()
    }

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: Actions

    /// Puts an item back on the clipboard so it can be pasted.
    func copy(_ item: ClipboardItem) {
        ignoreNextChange = true
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .link:
            if let text = item.text, let url = URL(string: text) {
                pasteboard.writeObjects([url as NSURL])
            }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let data = item.imageData { pasteboard.setData(data, forType: .png) }
        case .files:
            pasteboard.writeObjects(item.fileURLs.map { $0 as NSURL })
        }
        moveToTop(item.id)
    }

    func togglePin(_ item: ClipboardItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Clears everything except pinned items.
    func clearUnpinned() {
        items.removeAll { !$0.pinned }
        save()
    }

    // MARK: Capture

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if ignoreNextChange { ignoreNextChange = false; return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        guard let item = read(source: source) else { return }
        insert(item)
    }

    private func read(source: String?) -> ClipboardItem? {
        let now = Date()

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return ClipboardItem(id: UUID(), kind: .files, text: urls.map(\.path).joined(separator: "\n"), sourceApp: source, copiedAt: now, pinned: false)
        }
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            let isLink = !trimmed.contains(" ") && (trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://")) && URL(string: trimmed) != nil
            return ClipboardItem(id: UUID(), kind: isLink ? .link : .text, text: string, sourceApp: source, copiedAt: now, pinned: false)
        }
        if let image = NSImage(pasteboard: pasteboard), let png = Self.pngData(image, maxSide: 1600) {
            return ClipboardItem(id: UUID(), kind: .image, text: nil, sourceApp: source, copiedAt: now, pinned: false, imageData: png)
        }
        return nil
    }

    private func insert(_ new: ClipboardItem) {
        // Same text copied again: bump the existing entry instead of duplicating it.
        if new.kind != .image, let existing = items.firstIndex(where: { $0.kind == new.kind && $0.text == new.text }) {
            let pinned = items[existing].pinned
            items.remove(at: existing)
            var bumped = new
            bumped.pinned = pinned
            items.insert(bumped, at: 0)
        } else {
            items.insert(new, at: 0)
        }
        trim()
        save()
    }

    private func moveToTop(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        let item = items.remove(at: i)
        items.insert(item, at: 0)
        save()
    }

    private func trim() {
        var unpinnedSeen = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinnedSeen += 1
            return unpinnedSeen <= limit
        }
    }

    // MARK: Persistence (text, links, and file paths only)

    private func load() {
        guard let url = storeURL, let data = try? Data(contentsOf: url) else { return }
        items = (try? JSONDecoder().decode([ClipboardItem].self, from: data)) ?? []
    }

    private func save() {
        guard let url = storeURL else { return }
        let persistable = items.filter { $0.kind != .image }
        if let data = try? JSONEncoder().encode(persistable) {
            try? data.write(to: url, options: [.atomic])
        }
    }

    private static func pngData(_ image: NSImage, maxSide: CGFloat) -> Data? {
        guard let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        let w = CGFloat(cg.width), h = CGFloat(cg.height)
        let scale = min(1, maxSide / max(w, h))
        let size = NSSize(width: (w * scale).rounded(), height: (h * scale).rounded())
        guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width), pixelsHigh: Int(size.height),
                                         bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                         colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        NSGraphicsContext.current?.cgContext.draw(cg, in: CGRect(origin: .zero, size: size))
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }
}
